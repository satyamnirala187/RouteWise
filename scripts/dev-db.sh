#!/usr/bin/env bash
# Local PostgreSQL for RouteWise development and tests (no admin rights, no system install).
#
#   scripts/dev-db.sh install   # download + verify official PostgreSQL 18.6 macOS binaries into .local/
#   scripts/dev-db.sh init      # create the cluster, roles and databases; write secrets to .env
#   scripts/dev-db.sh start | stop | status | psql | create-db routewise_e2e
#
# The cluster lives in .local/pgdata (git-ignored), listens on 127.0.0.1 only, uses
# SCRAM-SHA-256 passwords, and runs as the current user. Delete .local/ to remove it.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LOCAL="$ROOT/.local"
PGBIN="$LOCAL/postgres/pgsql/bin"
PGDATA="$LOCAL/pgdata"
PORT="${ROUTEWISE_PG_PORT:-54329}"
ENV_FILE="$ROOT/.env"
ZIP_URL="https://get.enterprisedb.com/postgresql/postgresql-18.6-5-osx-binaries.zip"
ZIP_SHA256="a4147b2b9476a9d64f0b3ecc0112ca5ed3dc8eb217331e5b519fbdc608f7d30b"  # recorded 2026-10-13
EXPECTED_SIGNER="Developer ID Application: EnterpriseDB Corporation (26QKX55P9K)"

rand() { python3 -c 'import secrets; print(secrets.token_urlsafe(32))'; }

install() {
  mkdir -p "$LOCAL/downloads/postgres" "$LOCAL/postgres"
  local zip="$LOCAL/downloads/postgres/$(basename "$ZIP_URL")"
  [ -f "$zip" ] || curl -sS -L --retry 3 -o "$zip" "$ZIP_URL"
  echo "$ZIP_SHA256  $zip" | shasum -a 256 -c -
  [ -x "$PGBIN/postgres" ] || (cd "$LOCAL/postgres" && unzip -q "$zip")
  codesign -v "$PGBIN/postgres"
  local sig; sig="$(codesign -dvv "$PGBIN/postgres" 2>&1)"  # capture first: grep -q + pipefail misreports SIGPIPE
  grep -qF "Authority=$EXPECTED_SIGNER" <<<"$sig" || { echo "unexpected signer"; exit 1; }
  "$PGBIN/postgres" --version
}

init() {
  [ -x "$PGBIN/initdb" ] || install
  if [ -d "$PGDATA" ]; then echo "cluster already exists at $PGDATA"; return; fi
  touch "$ENV_FILE"; chmod 600 "$ENV_FILE"
  local superpw apppw secret
  superpw="$(rand)"; apppw="$(rand)"; secret="$(rand)"
  local pwfile; pwfile="$(mktemp)"; printf '%s' "$superpw" > "$pwfile"
  "$PGBIN/initdb" -D "$PGDATA" -U routewise_super --auth=scram-sha-256 --pwfile="$pwfile" --encoding=UTF8 --locale=C >/dev/null
  rm -f "$pwfile"
  {
    echo "listen_addresses = '127.0.0.1'"
    echo "port = $PORT"
    echo "unix_socket_directories = '$PGDATA'"
    echo "password_encryption = 'scram-sha-256'"
    echo "log_statement = 'none'"          # never log SQL text (it can contain customer data)
    echo "log_min_error_statement = 'panic'"
  } >> "$PGDATA/postgresql.conf"
  start
  PGPASSWORD="$superpw" "$PGBIN/psql" -h 127.0.0.1 -p "$PORT" -U routewise_super -d postgres -v ON_ERROR_STOP=1 -q <<SQL
CREATE ROLE routewise_app LOGIN PASSWORD '$apppw';
CREATE DATABASE routewise_dev OWNER routewise_app;
CREATE DATABASE routewise_test OWNER routewise_app;
SQL
  {
    echo "# Local development secrets (git-ignored). Generated by scripts/dev-db.sh on $(date -u +%F)."
    echo "ROUTEWISE_PG_SUPERUSER_PASSWORD=$superpw"
    echo "DATABASE_URL=postgresql+psycopg://routewise_app:$apppw@127.0.0.1:$PORT/routewise_dev"
    echo "TEST_DATABASE_URL=postgresql+psycopg://routewise_app:$apppw@127.0.0.1:$PORT/routewise_test"
    echo "ROUTEWISE_SECRET_KEY=$secret"
    echo "ROUTEWISE_ENV=development"
  } >> "$ENV_FILE"
  echo "cluster ready on 127.0.0.1:$PORT; credentials written to .env (git-ignored)"
}

start() {
  if "$PGBIN/pg_ctl" -D "$PGDATA" status >/dev/null 2>&1; then echo "already running"; return; fi
  "$PGBIN/pg_ctl" -D "$PGDATA" -l "$LOCAL/postgres.log" -w start >/dev/null && echo "started on 127.0.0.1:$PORT"
}

stop() { "$PGBIN/pg_ctl" -D "$PGDATA" -m fast stop; }
create_db() {  # extra database owned by the app role, e.g. routewise_e2e
  [[ "${1:-}" =~ ^routewise_[a-z0-9_]+$ ]] || { echo "name must match routewise_[a-z0-9_]+"; exit 2; }
  set -a; . "$ENV_FILE"; set +a
  local exists
  exists="$(PGPASSWORD="$ROUTEWISE_PG_SUPERUSER_PASSWORD" "$PGBIN/psql" -h 127.0.0.1 -p "$PORT" -U routewise_super -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname = '$1'")"
  if [ "$exists" = "1" ]; then echo "$1 exists"; return; fi
  PGPASSWORD="$ROUTEWISE_PG_SUPERUSER_PASSWORD" "$PGBIN/psql" -h 127.0.0.1 -p "$PORT" -U routewise_super -d postgres -q -c "CREATE DATABASE $1 OWNER routewise_app" && echo "created $1"
}
status() { "$PGBIN/pg_ctl" -D "$PGDATA" status; "$PGBIN/pg_isready" -h 127.0.0.1 -p "$PORT"; }
psql_() {
  # shellcheck disable=SC1090
  set -a; . "$ENV_FILE"; set +a
  PGPASSWORD="$ROUTEWISE_PG_SUPERUSER_PASSWORD" "$PGBIN/psql" -h 127.0.0.1 -p "$PORT" -U routewise_super -d routewise_dev "$@"
}

case "${1:-}" in
  install) install ;;
  init) init ;;
  start) start ;;
  stop) stop ;;
  status) status ;;
  psql) shift; psql_ "$@" ;;
  create-db) shift; create_db "${1:-}" ;;
  *) echo "usage: $0 install|init|start|stop|status|psql|create-db NAME"; exit 2 ;;
esac
