"""Step 4C: same-building stop groups.

A stop group makes several orders one navigation stop. It is admin-confirmed metadata on the
orders (`orders.building_id`); there is no table of its own. Chosen LOCAL implementation default
(owner instruction for 4C, not an independently approved permanent policy; plan Q4-1):

- Groups are suggested only for orders of ONE round whose stored pins are resolved, valid (inside
  the service area) and EXACTLY equal (the same stored latitude and longitude). Nearby pins,
  names, products and address text never suggest or form a group.
- Nothing is grouped until an admin confirms ("Group as one stop"). Identical pins may be
  different entrances, so leaving them separate is a normal, preserved choice.
- The group id is generated by the server (random, opaque); a client cannot choose or reuse one.
- A group has at least two members. Removing an order, or a member's pin actually changing,
  leaves the group; a group left with one member dissolves.
- Grouping changes only `building_id` (plus the order's `version`/`updated_at`, as every order
  edit does). It never changes a status, any customer detail, an owner lock, first-delivery
  priority or an assignment.

Planning input. A group change is an admin order edit: the round's `input_version` (stale
in-flight solves, rider reroutes included) and `route_version` (the saved plan is out of date)
both move, once per request. Saved plans and rider revisions are immutable and are not edited.

Locking and versions. Every operation that can change group membership (create, remove, a pin
edit of a grouped order) locks ALL the order rows it may touch FOR NO KEY UPDATE, in ascending id
order and in one statement (the same discipline as the bulk owner lock), and only afterwards
updates the round row through `bump_round_input`: order rows (sorted) -> round, the documented
order-edit order (planning.py), so no new wait cycle exists. Plan commits never lock order rows.
The set to lock is read just before locking it; that is safe because a group never gains a member
without its id changing: forming or extending a group gives every member a fresh id AND a new
version, so any request made from an older view fails the version check on a listed order, and the
rows are re-read under their locks before any rule is applied. A request is applied completely or
not at all, and a refused request changes nothing.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import select
from sqlalchemy.orm import Session as DBSession

from .config import ServiceArea
from .models import Order
from .riders import bump_round_input

MAX_GROUP_ORDERS = 100  # orders in one "Group as one stop" request


class GroupRefused(Exception):
    """A coded refusal; nothing was changed."""

    def __init__(self, status: int, code: str, message: str, details: list | None = None):
        super().__init__(f"{code}: {message}")
        self.status, self.code, self.message, self.details = status, code, message, details or []

    def body(self) -> dict:
        return {"code": self.code, "message": self.message, "details": self.details}


# ------------------------------------------------------------------ pins


def pin_of(o: Order) -> tuple[float, float] | None:
    """The stored pin, or None if the order has no resolved pin. Equality is exact, on purpose."""
    if o.location_state == "resolved" and o.lat is not None and o.lng is not None:
        return (o.lat, o.lng)
    return None


def valid_pin(o: Order, area: ServiceArea) -> bool:
    """Resolved and inside the service area: the same gate that lets an order reach the planner."""
    pin = pin_of(o)
    return pin is not None and area.contains(*pin)


# ------------------------------------------------------------------ locking


def lock_orders(db: DBSession, ids) -> dict[uuid.UUID, Order]:
    """Lock these order rows (FOR NO KEY UPDATE) in ascending id order and re-read them."""
    rows = db.scalars(select(Order).where(Order.id.in_(list(ids))).order_by(Order.id)
                      .with_for_update(key_share=True).execution_options(populate_existing=True)).all()
    return {o.id: o for o in rows}


def member_ids(db: DBSession, round_id: uuid.UUID, building_id: str) -> set[uuid.UUID]:
    return set(db.scalars(select(Order.id).where(Order.round_id == round_id, Order.building_id == building_id)).all())


def lock_for_pin_edit(db: DBSession, order_id: uuid.UUID) -> dict[uuid.UUID, Order] | None:
    """Lock an order about to get a new pin, and its whole group if it has one. None: no such order.

    The caller then checks the order's version; if the order was grouped or ungrouped since the
    admin's view, its version moved and the edit is refused (see the module docstring)."""
    row = db.execute(select(Order.round_id, Order.building_id).where(Order.id == order_id)).first()
    if row is None:
        return None
    round_id, building_id = row
    return lock_orders(db, {order_id} | (member_ids(db, round_id, building_id) if building_id else set()))


# ------------------------------------------------------------------ views (order codes only)


def suggestable(o: Order, area: ServiceArea) -> bool:
    """May this order be suggested for a group? The ONE rule behind the badges and the panel: a resolved
    pin inside the service area (the gate that lets an order reach the planner), and not Completed."""
    return valid_pin(o, area) and o.status != "Completed"


def stop_group_fields(orders: list[Order], area: ServiceArea) -> dict[uuid.UUID, dict]:
    """`stop_group` and `same_pin_as` for every order of ONE round. Order codes only; never a
    coordinate. `same_pin_as` lists the other orders with the identical pin, only while both are
    suggestable (see `suggestable`), whether or not they are grouped: a suggestion, never an action.
    `stop_group` is the existing membership, reported as it is, whatever the pin."""
    by_group: dict[str, list[Order]] = {}
    by_pin: dict[tuple[float, float], list[Order]] = {}
    for o in orders:
        if o.building_id:
            by_group.setdefault(o.building_id, []).append(o)
        if suggestable(o, area):
            by_pin.setdefault(pin_of(o), []).append(o)
    out: dict[uuid.UUID, dict] = {}
    for o in orders:
        group = None
        if o.building_id:
            members = sorted(m.order_code for m in by_group[o.building_id])
            group = {"id": o.building_id, "size": len(members), "members": members}
        same = (sorted(m.order_code for m in by_pin[pin_of(o)] if m.id != o.id) if suggestable(o, area) else [])
        out[o.id] = {"stop_group": group, "same_pin_as": same}
    return out


def fields_for_round(db: DBSession, round_id: uuid.UUID, area: ServiceArea) -> dict[uuid.UUID, dict]:
    orders = db.scalars(select(Order).where(Order.round_id == round_id)
                        .execution_options(populate_existing=True)).all()
    return stop_group_fields(list(orders), area)


def _ref(o: Order) -> dict:
    return {"id": str(o.id), "order_code": o.order_code, "status": o.status, "version": o.version}


def overview(orders: list[Order], area: ServiceArea) -> dict:
    """Groups and same-pin suggestions for the admin Orders page (order codes and versions only)."""
    groups: dict[str, list[Order]] = {}
    by_pin: dict[tuple[float, float], list[Order]] = {}
    for o in sorted(orders, key=lambda o: o.order_code):
        if o.building_id:
            groups.setdefault(o.building_id, []).append(o)
        if suggestable(o, area):
            by_pin.setdefault(pin_of(o), []).append(o)
    suggestions = []
    for members in by_pin.values():
        ids = {m.building_id for m in members}
        if len(members) >= 2 and not (len(ids) == 1 and None not in ids):  # not already one complete group
            suggestions.append({"orders": [_ref(m) | {"stop_group": m.building_id} for m in members]})
    suggestions.sort(key=lambda s: s["orders"][0]["order_code"])
    return {"groups": sorted(({"id": gid, "orders": [_ref(m) for m in ms]} for gid, ms in groups.items()),
                             key=lambda g: g["orders"][0]["order_code"]),
            "suggestions": suggestions}


# ------------------------------------------------------------------ create


def create_group(db: DBSession, round_id: uuid.UUID, requested: list[tuple[uuid.UUID, int]], area: ServiceArea,
                 now: datetime) -> tuple[bool, list[Order]]:
    """Make exactly these orders one stop group. Returns (changed, the group's orders).

    Refused with nothing changed unless: every order is in this round, no version is stale, every
    pin is resolved and inside the area, all pins are exactly equal, and every existing group that
    a listed order belongs to is listed completely (a group is never split silently). The group
    gets a fresh server-generated id; listed orders that were in a group leave it, so the new group
    replaces them. Submitting a group exactly as it already is changes nothing."""
    ids = [i for i, _ in requested]
    if len(set(ids)) != len(ids):
        raise GroupRefused(422, "DUPLICATE_ORDERS", "Each order may appear only once.")
    if len(ids) < 2:
        raise GroupRefused(422, "GROUP_TOO_SMALL", "A stop group needs at least two orders.")
    if len(ids) > MAX_GROUP_ORDERS:
        raise GroupRefused(422, "GROUP_TOO_LARGE", f"A stop group can hold at most {MAX_GROUP_ORDERS} orders per request.")
    rounds = dict(db.execute(select(Order.id, Order.round_id).where(Order.id.in_(ids))).all())
    if len(rounds) != len(ids) or any(r != round_id for r in rounds.values()):
        raise GroupRefused(404, "NOT_IN_ROUND", "Some orders are not part of this round.")
    touched = {b for b in db.scalars(select(Order.building_id).where(Order.id.in_(ids), Order.building_id.is_not(None))).all()}
    extra: set[uuid.UUID] = set()
    for b in touched:
        extra |= member_ids(db, round_id, b)
    locked = lock_orders(db, set(ids) | extra)
    listed = [locked[i] for i in ids]
    version_of = dict(requested)
    stale = sorted(o.order_code for o in listed if o.version != version_of[o.id])
    if stale:
        raise GroupRefused(409, "STALE_ORDERS", "These orders changed since you opened them; reload and try again.", stale)
    bad = sorted(o.order_code for o in listed if not valid_pin(o, area))
    if bad:
        raise GroupRefused(422, "LOCATION_NOT_VALID", "Only orders with a valid pin inside the service area can be grouped.", bad)
    if len({pin_of(o) for o in listed}) != 1:
        raise GroupRefused(422, "PINS_DIFFER", "Only orders with exactly the same pin can share a stop. Nearby pins are "
                           "never grouped.", sorted(o.order_code for o in listed))
    outside = sorted(o.order_code for i, o in locked.items() if i not in set(ids) and o.building_id in touched)
    if outside:
        raise GroupRefused(409, "GROUP_INCOMPLETE", "These orders already share a stop with orders you did not select. "
                           "Select the whole group, or remove them from it first.", outside)
    if len(touched) == 1 and extra == set(ids):
        return False, listed  # exactly the existing group: nothing to do
    building_id = uuid.uuid4().hex
    for o in listed:
        o.building_id, o.version, o.updated_at = building_id, o.version + 1, now
    bump_round_input(db, round_id)
    db.flush()
    return True, listed


# ------------------------------------------------------------------ remove


def ungroup_order(db: DBSession, order_id: uuid.UUID, version: int, now: datetime) -> tuple[Order, list[Order], list[Order]]:
    """Take one order out of its group. Returns (the order, orders freed by dissolving a group that
    would have had one member, the orders that remain grouped)."""
    round_id = db.scalar(select(Order.round_id).where(Order.id == order_id))
    if round_id is None:
        raise GroupRefused(404, "NOT_FOUND", "Order not found")
    building_id = db.scalar(select(Order.building_id).where(Order.id == order_id))
    locked = lock_orders(db, {order_id} | (member_ids(db, round_id, building_id) if building_id else set()))
    order = locked[order_id]
    if order.version != version:
        raise GroupRefused(409, "STALE_ORDERS", "This order changed since you opened it; reload and try again.",
                           [order.order_code])
    if order.building_id is None:
        raise GroupRefused(409, "NOT_GROUPED", "This order is not in a stop group.", [order.order_code])
    rest = [o for o in locked.values() if o.id != order_id and o.building_id == order.building_id]
    order.building_id, order.version, order.updated_at = None, order.version + 1, now
    freed: list[Order] = []
    if len(rest) == 1:  # a group of one is not a group
        rest[0].building_id, rest[0].version, rest[0].updated_at = None, rest[0].version + 1, now
        freed, rest = [rest[0]], []
    bump_round_input(db, round_id)
    db.flush()
    return order, freed, rest


# ------------------------------------------------------------------ pin changes


def leave_group_on_pin_change(order: Order, locked: dict[uuid.UUID, Order], before: tuple[float, float] | None,
                              now: datetime) -> dict | None:
    """After an order's pin was re-applied: if it was grouped and the pin ACTUALLY changed (a different
    pin, or no resolved pin any more), the order leaves its group, and a group left with one
    member dissolves. The caller bumps the round (a pin change always does). Returns a notice for
    the admin, or None if nothing changed. `locked` is `lock_for_pin_edit`'s result."""
    if order.building_id is None or pin_of(order) == before:
        return None
    building_id, order.building_id = order.building_id, None
    rest = [o for o in locked.values() if o.id != order.id and o.building_id == building_id]
    freed = []
    if len(rest) == 1:
        rest[0].building_id, rest[0].version, rest[0].updated_at = None, rest[0].version + 1, now
        freed = [rest[0].order_code]
        rest = []
    message = f"{order.order_code} left its stop group because its pin changed."
    if freed:
        message += f" {freed[0]} was the only order left in the group, so the group was dissolved."
    elif rest:
        message += f" The group still has {len(rest)} order(s): {', '.join(sorted(o.order_code for o in rest))}."
    return {"message": message, "freed": freed, "remaining": sorted(o.order_code for o in rest)}
